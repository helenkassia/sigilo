const PDF = new TextEncoder().encode("%PDF-1.4\n1 0 obj<<>>endobj\ntrailer<<>>\n%%EOF\n");

const imagem = (bytes = JPEG, extra = {}) => ({
  tipo: "imagem",
  mime: "image/jpeg",
  nome: "foto.jpg",
  texto: "legenda",
  bytes: bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes),
  ...extra,
});
const pdf = (extra = {}) => ({
  tipo: "pdf",
  mime: "application/pdf",
  nome: "doc.pdf",
  texto: "",
  bytes: PDF.slice(),
  ...extra,
});
const decode = (env) => JSON.parse(Buffer.from(env, "base64").toString());
const encode = (env) => Buffer.from(JSON.stringify(env)).toString("base64");

test("imagem v4 abre para remetente e destinatário com legenda", async () => {
  const arquivo = imagem();
  const envelope = await C.sealFile(ana, recipients, arquivo, context);
  assert.equal(decode(envelope).v, 4);
  assert.ok(Buffer.from(envelope, "base64").length < 5 * 1024 * 1024);
  for (const who of [ana, bia]) {
    const result = await C.open(who, C.eu(ana), envelope);
    assert.equal(result.texto, "legenda");
    assert.equal(result.arquivo.tipo, "imagem");
    assert.equal(result.arquivo.mime, "image/jpeg");
    assert.deepEqual(result.arquivo.bytes, arquivo.bytes);
  }
  await assert.rejects(C.open(outsider, C.eu(ana), envelope));
});

test("pdf v4 e buckets de padding não revelam mime no cabeçalho", async () => {
  const envelope = await C.sealFile(ana, recipients, pdf(), context);
  const header = decode(envelope);
  assert.equal(header.v, 4);
  assert.equal(JSON.stringify(header).includes("application/pdf"), false);
  assert.equal(JSON.stringify(header).includes("doc.pdf"), false);
  const result = await C.open(bia, C.eu(ana), envelope);
  assert.equal(result.arquivo.tipo, "pdf");
  assert.equal(result.arquivo.nome, "doc.pdf");
});

test("arquivo autentica ciphertext e cabeçalho de roteamento", async () => {
  const envelope = await C.sealFile(ana, recipients, imagem(), context);
  for (const field of ["ct", "canal", "dm", "from", "v"]) {
    const modified = decode(envelope);
    modified[field] = field === "v" ? 3 : field === "ct" ? (modified.ct[0] === "A" ? "B" : "A") + modified.ct.slice(1) : "alterado";
    await assert.rejects(C.open(bia, C.eu(ana), encode(modified)));
  }
});

test("entrada de arquivo rejeita magic bytes, SVG e tamanho inválido", async () => {
  const big = new Uint8Array(C.FILE_MAX_BYTES + 1);
  big.set(JPEG.subarray(0, 3), 0);
  for (const arquivo of [
    imagem(new Uint8Array([0x00, 0x01, 0x02, 0x03])),
    { ...imagem(), mime: "image/svg+xml" },
    { ...imagem(), mime: "image/png" },
    { ...imagem(), bytes: big },
    { ...pdf(), mime: "image/jpeg" },
  ]) {
    await assert.rejects(C.sealFile(ana, recipients, arquivo, context));
  }
});
